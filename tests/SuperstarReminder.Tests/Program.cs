using SuperstarReminder.Domain;
var passed=0;
void Check(string name,bool condition){if(!condition)throw new Exception("FAIL: "+name);passed++;Console.WriteLine("PASS: "+name);}
void Reject(string name,Action action){try{action();}catch(ArgumentException){Check(name,true);return;}Check(name,false);}
DateTimeOffset At(string x)=>DateTimeOffset.Parse(x,System.Globalization.CultureInfo.InvariantCulture);
var start=At("2026-10-16T09:00:00Z");
var r=new Reminder(Guid.NewGuid(),"Water","Ready?",true,ScheduleType.Interval,start,45,new HashSet<DayOfWeek>(),null,null,"UTC",null);
Check("First occurrence before anchor",ScheduleCalculator.Next(r,start.AddSeconds(-1))==start);
Check("Strictly after anchor",ScheduleCalculator.Next(r,start)==start.AddMinutes(45));
Check("Interval stays anchored after missed times",ScheduleCalculator.Next(r,start.AddMinutes(100))==start.AddMinutes(135));
Check("Disabled schedule",ScheduleCalculator.Next(r with{Enabled=false},start) is null);
var hours=r with{ActiveFrom=new TimeOnly(9,0),ActiveTo=new TimeOnly(17,0)};
Check("Active start inclusive",ScheduleCalculator.IsActive(hours,start));
Check("Active end exclusive",!ScheduleCalculator.IsActive(hours,start.AddHours(8)));
Check("Skip inactive evening",ScheduleCalculator.Next(hours,At("2026-10-16T17:00:00Z"))==At("2026-10-17T09:00:00Z"));
var overnight=r with{ActiveFrom=new TimeOnly(22,0),ActiveTo=new TimeOnly(6,0)};
Check("Overnight late",ScheduleCalculator.IsActive(overnight,At("2026-10-16T23:00:00Z")));
Check("Overnight early",ScheduleCalculator.IsActive(overnight,At("2026-10-17T05:00:00Z")));
Check("Overnight day excluded",!ScheduleCalculator.IsActive(overnight,start));
Check("Overnight next aligned to anchor",ScheduleCalculator.Next(overnight,start)==At("2026-10-16T22:30:00Z"));
var daily=r with{ScheduleType=ScheduleType.Daily,IntervalMinutes=null};
Check("Daily tomorrow",ScheduleCalculator.Next(daily,start)==start.AddDays(1));
Check("Daily today before time",ScheduleCalculator.Next(daily,start.AddMinutes(-1))==start);
var weekdays=daily with{ScheduleType=ScheduleType.Weekdays,Weekdays=new HashSet<DayOfWeek>{DayOfWeek.Monday}};
Check("Selected weekday only",ScheduleCalculator.Next(weekdays,start)==At("2026-10-19T09:00:00Z"));
var once=daily with{ScheduleType=ScheduleType.OneTime};
Check("One-time future",ScheduleCalculator.Next(once,start.AddSeconds(-1))==start);
Check("One-time consumed",ScheduleCalculator.Next(once,start) is null);
Reject("Missing weekday rejected",()=>ScheduleCalculator.Validate(weekdays with{Weekdays=new HashSet<DayOfWeek>()}));
Reject("Zero interval rejected",()=>ScheduleCalculator.Validate(r with{IntervalMinutes=0}));
Reject("Empty title rejected",()=>ScheduleCalculator.Validate(r with{Title=" "}));
Reject("Mismatched hours rejected",()=>ScheduleCalculator.Validate(r with{ActiveFrom=new TimeOnly(9,0)}));
Reject("Equal hours rejected",()=>ScheduleCalculator.Validate(r with{ActiveFrom=new TimeOnly(9,0),ActiveTo=new TimeOnly(9,0)}));
Reject("Inactive one-time rejected",()=>ScheduleCalculator.Validate(once with{ActiveFrom=new TimeOnly(10,0),ActiveTo=new TimeOnly(11,0)}));
var zone=TimeZoneInfo.FindSystemTimeZoneById("America/New_York");
Check("DST nonexistent time moves forward",ScheduleCalculator.ToUtc(new DateTime(2026,3,8,2,30,0),zone)==At("2026-03-08T07:00:00Z"));
Check("DST repeated time resolves once",ScheduleCalculator.ToUtc(new DateTime(2026,11,1,1,30,0),zone)==At("2026-11-01T05:30:00Z"));
var dst=daily with{TimeZoneId=zone.Id,StartsAtUtc=At("2026-03-07T14:00:00Z")};
Check("Daily time stable across DST",ScheduleCalculator.Next(dst,At("2026-03-07T14:00:00Z"))==At("2026-03-08T13:00:00Z"));
Check("Larger stock character",OverlayPresentation.CharacterHeight(1000,.30)==300);
Check("Small desktop character fits",OverlayPresentation.CharacterHeight(450,.40)<=180);
Check("High DPI uses logical height",OverlayPresentation.CharacterHeight(1600/2d,.30)==240);
Check("Bubble follows actual height",Math.Abs(OverlayPresentation.BannerTop(500,300,170)-(500+300*.035-6-170))<.01);
Check("Yes never selects running",OverlayPresentation.ExitAction(ReminderOutcome.Yes,true)=="walkLeft");
Check("No uses disappointed walk",OverlayPresentation.ExitAction(ReminderOutcome.No,false)=="sadWalkRight");
Check("Snooze uses disappointed walk",OverlayPresentation.ExitAction(ReminderOutcome.Snoozed,true)=="sadWalkLeft");
Check("Sad walk is slower than approval",OverlayPresentation.WalkMilliseconds(400,false)>OverlayPresentation.WalkMilliseconds(400,true));
Console.WriteLine($"{passed} scheduling checks passed.");
